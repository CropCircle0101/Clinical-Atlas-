export const demoClinics: Clinic[] = entries.map(
  (
    [
      name,
      city,
      state,
      postalCode,
      latitude,
      longitude,
      specialtyIds,
      serviceIds,
      priceFrom,
      telehealth,
    ],
    i,
  ) => {
    const id = `demo-${String(i + 1).padStart(2, "0")}`;
    return {
      id,
      slug: name
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/-$/, ""),
      name,
      description: `${name} is a fictional ${specialties.find((s) => s.id === specialtyIds[0])?.name.toLowerCase()} practice in ${city}, created to demonstrate ClinicAtlas. Its offerings, prices, coverage and address are sample information only.`,
      website: null,
      phone: null,
      npi: null,
      isDemo: true,
      status: "published",
      telehealth,
      priceFrom,
      priceNote: priceFrom
        ? "Illustrative starting price; not a quote. Service-specific costs vary."
        : null,
      insurance: i % 4 === 0 ? [] : ["Medicare", i % 2 ? "Aetna" : "Blue Cross Blue Shield"],
      specialties: specialties
        .filter((s) => specialtyIds.includes(s.id))
        .map(({ id, name }) => ({ id, name })),
      services: services
        .filter((s) => serviceIds.includes(s.id))
        .map(({ id, name }) => ({ id, name })),
      locations: [
        {
          id: `${id}-loc`,
          address: `${100 + i * 10} Example Avenue (fictional)`,
          city,
          state,
          postalCode,
          latitude,
          longitude,
        },
      ],
      sources: [
        {
          id: `${id}-source`,
          label: "Fictional demo fixture · not independently verified",
          url: "https://example.com",
          scope: "identity",
          status: "pending",
          checkedAt: null,
        },
      ],
      lastVerifiedAt: null,
    };
  },
);
